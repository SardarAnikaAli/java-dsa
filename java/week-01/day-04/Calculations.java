public class Calculations {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;

        System.out.println(a + b * 2);
        System.out.println((a + b) * 2);
        System.out.println(a % b);

        boolean result = a > 5 && b < 5;
        System.out.println(result);
    }
}